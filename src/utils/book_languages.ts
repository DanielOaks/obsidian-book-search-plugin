/** Books without any text, such as art books or photo collections. */
export const NO_TEXT_LANGUAGE = 'No text';

/**
 * Languages that a provider covers exclusively, used when it reports no language information at
 * all. OpenBD only indexes Japanese titles and Naver Book Search only indexes Korean ones, so
 * falling back to the user's default language would be wrong for both.
 */
export const JAPANESE_LANGUAGE = LANGUAGE_NAMES.ja;
export const KOREAN_LANGUAGE = LANGUAGE_NAMES.ko;

/** Language used when neither the provider nor the user's settings name one. */
export const FALLBACK_LANGUAGE = LANGUAGE_NAMES.en;

/**
 * Language to record for a book that has no language information at all, such as a manually
 * created entry. Providers bound to a single market always report their own language, the others
 * defer to the user's default language.
 */
export function getProviderDefaultLanguage(provider: ServiceProvider, defaultLanguage?: string): string {
  switch (provider) {
    case ServiceProvider.naver:
      return KOREAN_LANGUAGE;
    case ServiceProvider.openbd:
      return JAPANESE_LANGUAGE;
    default:
      return defaultLanguage?.trim() || FALLBACK_LANGUAGE;
  }
}

/** Code values that describe the absence of text rather than a language. */
export const NO_TEXT_CODES = new Set(['zxx']);

/**
 * Resolves a language code to a display name.
 *
 * @returns the display name, or `undefined` when the code is unknown. Unrecognised codes are
 * deliberately not passed through so that a default can be used instead.
 */
export function getLanguageName(code?: string): string | undefined {
  const normalized = code?.trim().toLowerCase().replace(/_/g, '-');
  if (!normalized) return undefined;

  if (NO_TEXT_CODES.has(normalized)) return NO_TEXT_LANGUAGE;

  if (LANGUAGE_NAMES[normalized]) return LANGUAGE_NAMES[normalized];
  if (EXTRA_LANGUAGE_NAMES[normalized]) return EXTRA_LANGUAGE_NAMES[normalized];

  const alias = LANGUAGE_ALIASES[normalized];
  if (alias) return LANGUAGE_NAMES[alias] ?? EXTRA_LANGUAGE_NAMES[alias];

  // Region variants such as `en-GB` or `zh-Hans` still identify a language
  const [base] = normalized.split('-');
  return base && base !== normalized ? getLanguageName(base) : undefined;
}

/**
 * Picks the language to record for a book.
 *
 * Records that list several languages almost always have the book's original language among them,
 * so the user's default language wins when it is present. Otherwise the first language that can be
 * resolved is used.
 *
 * @returns the display name, or `undefined` when none of the codes are recognised.
 */
export function resolveLanguage(codes?: string[], defaultLanguage?: string): string | undefined {
  const names = (codes ?? []).map(getLanguageName).filter((name): name is string => Boolean(name));
  if (!names.length) return undefined;

  const preferred = defaultLanguage?.trim().toLowerCase();
  return names.find(name => name.toLowerCase() === preferred) ?? names[0];
}
